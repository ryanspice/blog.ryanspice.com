import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const projectRoot = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const buildRoot = path.resolve(process.env.ADAPTER_OUT || path.join(projectRoot, 'build'));
const outputRoot = path.resolve(
	process.env.BLOG_PRIVATE_CONTENT_OUT || path.join(projectRoot, 'output', 'private-content')
);
const viteCacheRoot = path.resolve(
	process.env.VITE_CACHE_DIR || path.join(projectRoot, 'output', '.vite-private-content')
);
const siteId = (process.env.PUBLIC_SITE_ID || process.env.BLOG_SITE_ID || 'ryan').trim().toLowerCase();

if (siteId === 'canopy' && process.env.BLOG_PRIVATE_CONTENT_ALLOW_CANOPY !== '1') {
	console.log('Private draft content is not generated for the Canopy build.');
	process.exit(0);
}

function isInside(parent, child) {
	const relative = path.relative(parent, child);
	return relative === '' || (relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

async function resolvedDestination(directory) {
	try { return await fs.realpath(directory); }
	catch (error) {
		if (error?.code !== 'ENOENT') throw error;
		const parent = path.dirname(directory);
		if (parent === directory) throw error;
		return path.join(await resolvedDestination(parent), path.basename(directory));
	}
}

async function assertPrivateDestination() {
	// Reject links in every existing ancestor, including junctions on Windows.
	// A lexical path outside build/ can otherwise resolve into public output.
	for (let current = outputRoot; ; current = path.dirname(current)) {
		try {
			if ((await fs.lstat(current)).isSymbolicLink()) {
				throw new Error(`Refusing linked private content destination: ${current}`);
			}
		} catch (error) {
			if (error?.code !== 'ENOENT') throw error;
		}
		if (path.dirname(current) === current) break;
	}
	if (isInside(outputRoot, projectRoot) || isInside(outputRoot, buildRoot)) {
		throw new Error('Private output must not contain the project or public build.');
	}
	const forbidden = [
		['build', buildRoot],
		['static', path.join(projectRoot, 'static')],
		['src', path.join(projectRoot, 'src')]
	];
	const resolvedOutput = await resolvedDestination(outputRoot);
	for (const [label, directory] of forbidden) {
		const resolvedProtected = await resolvedDestination(directory);
		if (isInside(resolvedProtected, resolvedOutput) || isInside(resolvedOutput, resolvedProtected)) {
			throw new Error(`Private content must be disjoint from ${label}: ${outputRoot}`);
		}
	}
}

function validateSlug(slug) {
	if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
		throw new Error(`Private article has an unsafe slug: ${JSON.stringify(slug)}`);
	}
}

function withoutRawBody(article) {
	const { body, previousBody, ...safe } = article;
	return safe;
}

function normalizeOwnerHash(value) {
	const normalized = typeof value === 'string' ? value.trim().toLowerCase().replace(/^sha256:/, '') : '';
	return /^[a-f0-9]{64}$/.test(normalized) ? normalized : '';
}

async function resolveOwnerHash() {
	const fromEnvironment = normalizeOwnerHash(process.env.BLOG_OWNER_EMAIL_SHA256);
	if (fromEnvironment) return { hash: fromEnvironment, source: 'BLOG_OWNER_EMAIL_SHA256' };

	const pageSourcePath = path.join(projectRoot, 'src', 'routes', 'drafts', '[slug]', '+page.server.php');
	try {
		const source = await fs.readFile(pageSourcePath, 'utf8');
		const match = source.match(/return\s+'([a-f0-9]{64})'\s*;/i);
		if (match) return { hash: match[1].toLowerCase(), source: 'canonical PHP owner mapping' };
	} catch {
		// Missing canonical mapping falls through to a denied read endpoint.
	}

	return null;
}

function toManifestEntry(article) {
	return {
		...withoutRawBody(article),
		html: '',
		toc: []
	};
}

async function assertReplaceableOutput() {
	let entries;
	try {
		entries = await fs.readdir(outputRoot);
	} catch (error) {
		if (error?.code === 'ENOENT') return;
		throw error;
	}
	if (entries.length === 0) return;

	try {
		const marker = JSON.parse(await fs.readFile(path.join(outputRoot, 'manifest.json'), 'utf8'));
		if (
			marker?.privateDraftPayload === true &&
			marker?.packet === 'blog-repair-draft-confidentiality-and-microsoft-csp'
		) {
			return;
		}
	} catch {
		// Fall through to the refusal below.
	}

	throw new Error(`Refusing to replace private content not generated by this packet: ${outputRoot}`);
}

function validateUniqueSlugs(items, label) {
	const seen = new Set();
	for (const item of items) {
		validateSlug(item.slug);
		if (seen.has(item.slug)) {
			throw new Error(`Duplicate private ${label} slug: ${item.slug}`);
		}
		seen.add(item.slug);
	}
}

async function writePayload(privateArticles, privateBriefs) {
	const generatedAt = new Date().toISOString();
	validateUniqueSlugs(privateArticles, 'article');
	validateUniqueSlugs(privateBriefs, 'morning brief');

	await assertReplaceableOutput();
	const temporaryRoot = outputRoot;
	await fs.rm(temporaryRoot, { recursive: true, force: true });
	await fs.mkdir(temporaryRoot, { recursive: true, mode: 0o700 });
	await fs.mkdir(path.join(temporaryRoot, 'articles'), { mode: 0o700 });
	await fs.mkdir(path.join(temporaryRoot, 'briefs'), { mode: 0o700 });

	const guardSource = path.join(projectRoot, 'src', 'lib', 'server', 'php', 'owner-guard.php');
	await fs.copyFile(guardSource, path.join(temporaryRoot, 'owner-guard.php'));
	await fs.chmod(path.join(temporaryRoot, 'owner-guard.php'), 0o600);

	const owner = await resolveOwnerHash();
	if (owner) {
		await fs.writeFile(
			path.join(temporaryRoot, 'owner.json'),
			`${JSON.stringify({ ownerEmailSha256: owner.hash }, null, 2)}\n`,
			'utf8'
		);
		console.log(`Private owner mapping source: ${owner.source}`);
	} else {
		console.warn('Private owner mapping is missing; the private draft endpoint will deny requests until configured.');
	}

	const manifest = {
		privateDraftPayload: true,
		packet: 'blog-repair-draft-confidentiality-and-microsoft-csp',
		version: 1,
		generatedAt,
		articles: privateArticles.map((article) => ({ slug: article.slug, ...toManifestEntry(article) }))
	};
	await fs.writeFile(path.join(temporaryRoot, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

	for (const article of privateArticles) {
		const payload = {
			version: 1,
			generatedAt,
			article: { ...toManifestEntry(article), html: article.html, toc: article.toc }
		};
		await fs.writeFile(
			path.join(temporaryRoot, 'articles', `${article.slug}.json`),
			`${JSON.stringify(payload, null, 2)}\n`,
			'utf8'
		);
	}

	const briefManifest = {
		privateDraftPayload: true,
		packet: 'blog-repair-draft-confidentiality-and-microsoft-csp',
		kind: 'briefs',
		version: 1,
		generatedAt,
		briefs: privateBriefs.map((brief) => ({ slug: brief.slug, ...toManifestEntry(brief) }))
	};
	await fs.writeFile(
		path.join(temporaryRoot, 'briefs', 'manifest.json'),
		`${JSON.stringify(briefManifest, null, 2)}\n`,
		'utf8'
	);

	for (const brief of privateBriefs) {
		const payload = {
			version: 1,
			generatedAt,
			brief: { ...toManifestEntry(brief), html: brief.html, toc: brief.toc }
		};
		await fs.writeFile(
			path.join(temporaryRoot, 'briefs', `${brief.slug}.json`),
			`${JSON.stringify(payload, null, 2)}\n`,
			'utf8'
		);
	}

	return {
		articleCount: privateArticles.length,
		briefCount: privateBriefs.length,
		manifestPath: path.join(outputRoot, 'manifest.json'),
		briefManifestPath: path.join(outputRoot, 'briefs', 'manifest.json')
	};
}

// Every new file, including Vite cache files created by this process, is private
// on POSIX hosts. Windows deployments must additionally verify the host ACL.
process.umask(0o077);
await assertPrivateDestination();

const vite = await createServer({
	configFile: false,
	root: projectRoot,
	appType: 'custom',
	cacheDir: viteCacheRoot,
	logLevel: 'error',
	resolve: {
		preserveSymlinks: true
	},
	server: {
		hmr: false,
		middlewareMode: true
	}
});

try {
	const privateModule = await vite.ssrLoadModule('/src/lib/server/private-articles.ts');
	const privateArticles = privateModule.privateArticles;
	if (!Array.isArray(privateArticles)) {
		throw new Error('Private article module did not expose a privateArticles array.');
	}

	const briefModule = await vite.ssrLoadModule('/src/lib/server/private-briefs.ts');
	const privateBriefs = briefModule.visiblePrivateBriefs;
	if (!Array.isArray(privateBriefs)) {
		throw new Error('Private brief module did not expose a visiblePrivateBriefs array.');
	}

	const result = await writePayload(privateArticles, privateBriefs);
	console.log(
		`Private draft payload written: ${result.articleCount} article(s), ${result.briefCount} brief(s)`
	);
	console.log(`Private draft manifest: ${result.manifestPath}`);
	console.log(`Private brief manifest: ${result.briefManifestPath}`);
	console.log(`Private draft destination is outside the deployable build: ${outputRoot}`);
} finally {
	await vite.close();
}
